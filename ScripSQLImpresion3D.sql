CREATE DATABASE Impresion3D;

create table Clientes
(
	 Id_cliente_Cli UUID PRIMARY KEY DEFAULT gen_random_uuid(),
	 Nombre_Cli VARCHAR(100) NOT NULL,
	 Apellido_Cli VARCHAR(100) NOT NULL,
	 CorreoElectronico_Cli VARCHAR(300) NULL,
	 Zona_Cli VARCHAR(100) NOT NULL,
	 Telefono_Cli VARCHAR(20) NOT NULL UNIQUE,
	 Activo_Cli BOOLEAN DEFAULT TRUE NOT NULL
);

create table Categorias
(
	Id_Categoria_Cat INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	Nombre_Cat VARCHAR(100) NOT NULL UNIQUE
);

create table Productos
(
	Id_Productos_Prod INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	Id_Categoria_Prod INT NOT NULL REFERENCES Categorias(Id_Categoria_Cat),
	Nombre_Prod VARCHAR (100) NOT NULL,
	Precio_Prod NUMERIC(12,2) NOT NULL CHECK (precio_Prod > 0),
	Activo_Prod BOOLEAN DEFAULT TRUE NOT NULL
);

create table EstadoPedido
(
	Id_EstadoPedido_EST INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	Codigo_EST VARCHAR(30) NOT NULL UNIQUE,
	Estado_EST VARCHAR(30) NOT NULL
);


create table Pedidos
(
	Id_Pedido_Ped UUID PRIMARY KEY DEFAULT gen_random_uuid(),
	Id_cliente_Ped UUID NOT NULL REFERENCES Clientes(Id_cliente_Cli),
	Id_EstadoPedido_Ped INT NOT NULL REFERENCES EstadoPedido(Id_EstadoPedido_EST),
	NumeroPedido_Ped INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL UNIQUE,
	NotaPedido_Ped VARCHAR(300) NULL,
	Seguimiento_Ped VARCHAR(300) NULL,
	FechaPedido_Ped TIMESTAMPTZ NOT NULL DEFAULT now()
);

create table DetallePedido
(
	Id_DetallePedido_DPed INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	Id_Pedido_DPed UUID NOT NULL REFERENCES Pedidos(Id_Pedido_Ped) ON DELETE CASCADE,
	Id_Producto_DPed INT NOT NULL REFERENCES Productos(Id_Productos_Prod),
	Nombre_DPed VARCHAR (100) NOT NULL,
	Cantidad_DPed INT NOT NULL CHECK (Cantidad_DPed > 0),
	Precio_DPed NUMERIC(12,2) NOT NULL CHECK (Precio_DPed > 0),
	Importe_DPed NUMERIC(14,2) GENERATED ALWAYS AS (Cantidad_DPed * Precio_DPed) STORED
);

create table Usuarios
(
	Id_Usuario_U UUID PRIMARY KEY DEFAULT gen_random_uuid(),
	User_U VARCHAR(30) UNIQUE NOT NULL,
	Password_U TEXT NOT NULL,
	FechaCreacion_U TIMESTAMPTZ NOT NULL DEFAULT now(),
	Activo_U BOOLEAN DEFAULT TRUE NOT NULL
);


