CREATE OR REPLACE PROCEDURE sp_AgregarCliente(
	NOMBRE VARCHAR(100),
	APELLIDO VARCHAR(100),
	CORREO VARCHAR(300),
	ZONA VARCHAR(100),
	TELEFONO VARCHAR(20), 
	OUT ID_CLIENTE UUID
)
LANGUAGE plpgsql
AS $$
BEGIN
	INSERT INTO Clientes (Nombre_Cli, Apellido_Cli, CorreoElectronico_Cli, Zona_Cli, Telefono_Cli)
	VALUES (NOMBRE, APELLIDO, CORREO, ZONA, TELEFONO);

	RETURNING IdCliente_Cli INTO ID_CLIENTE;
END;
$$

CREATE OR REPLACE FUNCTION fn_AgregarCliente(
	NOMBRE VARCHAR(100),
	APELLIDO VARCHAR(100),
	CORREO VARCHAR(300),
	ZONA VARCHAR(100),
	TELEFONO VARCHAR(20)
)
RETURNS UUID
LANGUAGE plpgsql
AS $$
DECLARE
    ID_CLIENTE UUID;
BEGIN
	INSERT INTO Clientes (Nombre_Cli, Apellido_Cli, CorreoElectronico_Cli, Zona_Cli, Telefono_Cli)
	VALUES (NOMBRE, APELLIDO, CORREO, ZONA, TELEFONO);
    RETURNING IdCliente_Cli INTO ID_CLIENTE;

    RETURN ID_CLIENTE;
END;
$$;


CREATE OR REPLACE PROCEDURE sp_AgregarCategoria(
	NOMBRE VARCHAR(100)
)
LANGUAGE plpgsql
AS $$
BEGIN
	INSERT INTO Categorias (Nombre_cat)
	VALUES (NOMBRE);
END; 
$$


CREATE OR REPLACE PROCEDURE sp_AgregarProducto(
	ID_CATEGORIA INT, 
	NOMBRE VARCHAR(100),
	PRECIO NUMERIC(12,2)
)
LANGUAGE plpgsql
AS $$
BEGIN 
	INSERT INTO Productos (Id_Categoria_Prod, Nombre_Prod, Precio_Prod)
	VALUES (ID_CATEGORIA, NOMBRE, PRECIO);
END;
$$

